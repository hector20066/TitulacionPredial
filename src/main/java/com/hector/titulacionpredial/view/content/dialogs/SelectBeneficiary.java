    private void connectEvents() {
        btn_searchOri.addActionListener(e -> {
            
        });
        
        btn_select.addActionListener(e -> {
            confirmed = true;
            //codeBeneficiarySelected();
            closeMenu();
        });
        
        btn_cancel.addActionListener(e -> {
            confirmed = false;
            dispose();
            closeMenu();
        });
        
        txt_searchori.getDocument().addDocumentListener(new DocumentListener() {
            @Override
            public void insertUpdate(DocumentEvent e) {
                FilterUtils.filterTable(txt_searchori, jtbl_beneficiaries, "Buscar");
            }

            @Override
            public void removeUpdate(DocumentEvent e) {
                FilterUtils.filterTable(txt_searchori, jtbl_beneficiaries, "Buscar");
            }

            @Override
            public void changedUpdate(DocumentEvent e) {
                FilterUtils.filterTable(txt_searchori, jtbl_beneficiaries, "Buscar");
            }
        });
        
        txt_searchori.addFocusListener(new FocusAdapter() {
            @Override
            public void focusLost(FocusEvent e) {
                if (txt_searchori.getText().isBlank()) {
                    txt_searchori.setText("Buscar");
                }
            }
        });
        
        txt_searchori.addMouseListener(new MouseAdapter() {
            @Override
            public void mouseClicked(MouseEvent e) {
                if (txt_searchori.getText().equals("Buscar")) {
                    txt_searchori.setText("");
                }
            }
        });
    }
    
    private void closeMenu() {
        if (animator.isRunning()) {
            animator.stop();
        }
        
        show = false;
        animator.start();
    }
    
    public void loadBeneficiaries(List<DTOBeneficiarySimpleDetails> listBeneficiaries) {
        model.setRowCount(0);
        
        listBeneficiaries.forEach(e -> {
            Object[] data = new Object[]{e.getCode(), e.getFullName(), e.getId(), e.getCadastralReference()};
            model.addRow(data);
        });
    }
    
    public int codeBeneficiarySelected() {
        int code = 0;
        
        if (jtbl_beneficiaries.getSelectedRow() > -1) {
            code = Integer.parseInt(jtbl_beneficiaries.getValueAt(jtbl_beneficiaries.getSelectedRow(), 0).toString());
        }
        
        return code;
    }
    
    public boolean isConfirmed() {
        return confirmed;
    }
    
